
from decimal import Decimal
import uuid

from django.conf import settings
from django.core.validators import MinValueValidator
from django.db import models


class PayrollRecord(models.Model):
    class Status(models.TextChoices):
        DRAFT = "DRAFT", "Draft"
        LOCKED = "LOCKED", "Locked"
        PAID = "PAID", "Paid"

    employee = models.ForeignKey(
        "employees.Employee",
        on_delete=models.PROTECT,
        related_name="payroll_records",
    )

    year = models.PositiveIntegerField()
    month = models.PositiveSmallIntegerField()

    base_salary = models.DecimalField(
        max_digits=12,
        decimal_places=2,
    )

    lop_days = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        default=0,
    )

    lop_deduction = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=0,
    )

    net_salary = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=0,
    )

    # Total earnings before deductions.
    gross_salary = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=0,
    )

    # LOP deduction plus other salary deductions.
    total_deductions = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=0,
    )

    # Snapshot of earnings and deductions used for this payroll.
    salary_components = models.JSONField(
        default=list,
        blank=True,
    )

    status = models.CharField(
        max_length=10,
        choices=Status.choices,
        default=Status.DRAFT,
    )

    generated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["employee", "year", "month"],
                name="unique_employee_payroll_per_month",
            ),
        ]
        ordering = ["-year", "-month"]

    def __str__(self):
        return (
            f"{self.employee.employee_code} - "
            f"{self.month}/{self.year} - {self.status}"
        )


class SalaryPayment(models.Model):
    # One simulated payment per payroll record.
    payroll_record = models.OneToOneField(
        "payroll.PayrollRecord",
        on_delete=models.PROTECT,
        related_name="salary_payment",
    )

    # Unique reference generated by the backend.
    reference = models.UUIDField(
        default=uuid.uuid4,
        unique=True,
        editable=False,
    )

    # Amount is calculated by the backend.
    amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
    )

    # This is a simulated payment, not a real bank transfer.
    status = models.CharField(
        max_length=20,
        default="SIMULATED_SUCCESS",
    )

    paid_at = models.DateTimeField(auto_now_add=True)

    processed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="processed_salary_payments",
    )

    def __str__(self):
        return f"{self.reference} - {self.amount}"


class SalaryAdvance(models.Model):
    """An employee's request for a salary advance."""

    class Status(models.TextChoices):
        PENDING = "PENDING", "Pending"
        APPROVED = "APPROVED", "Approved"
        REJECTED = "REJECTED", "Rejected"
        DISBURSED = "DISBURSED", "Disbursed"
        COMPLETED = "COMPLETED", "Completed"

    employee = models.ForeignKey(
        "employees.Employee",
        on_delete=models.PROTECT,
        related_name="salary_advances",
    )

    requested_amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(Decimal("0.01"))],
    )

    approved_amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        null=True,
        blank=True,
        validators=[MinValueValidator(Decimal("0.01"))],
    )

    reason = models.TextField()

    repayment_installments = models.PositiveSmallIntegerField(
        default=1,
        validators=[MinValueValidator(1)],
    )

    status = models.CharField(
        max_length=12,
        choices=Status.choices,
        default=Status.PENDING,
        db_index=True,
    )

    review_comment = models.TextField(
        blank=True,
        default="",
    )

    reviewed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="reviewed_salary_advances",
    )

    reviewed_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    disbursed_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return (
            f"{self.employee.employee_code} - "
            f"{self.requested_amount} - {self.status}"
        )


class SalaryAdvanceRepayment(models.Model):
    """A repayment recorded against a salary advance."""

    advance = models.ForeignKey(
        SalaryAdvance,
        on_delete=models.PROTECT,
        related_name="repayments",
    )

    amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(Decimal("0.01"))],
    )

    repayment_date = models.DateField()

    payroll_record = models.ForeignKey(
        "payroll.PayrollRecord",
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="salary_advance_repayments",
    )

    recorded_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="recorded_advance_repayments",
    )

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-repayment_date", "-created_at"]

    def __str__(self):
        return f"Advance #{self.advance_id} - {self.amount}"


class EmployeeSalaryComponent(models.Model):
    """A recurring earning or deduction configured for an employee."""

    class ComponentType(models.TextChoices):
        EARNING = "EARNING", "Earning"
        DEDUCTION = "DEDUCTION", "Deduction"

    employee = models.ForeignKey(
        "employees.Employee",
        on_delete=models.PROTECT,
        related_name="salary_components",
    )

    name = models.CharField(max_length=100)

    component_type = models.CharField(
        max_length=10,
        choices=ComponentType.choices,
    )

    amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(Decimal("0.01"))],
    )

    is_active = models.BooleanField(default=True)

    effective_from = models.DateField()
    effective_to = models.DateField(
        null=True,
        blank=True,
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["employee_id", "component_type", "name"]
        constraints = [
            models.CheckConstraint(
                condition=models.Q(amount__gt=0),
                name="salary_component_amount_positive",
            ),
        ]

    def __str__(self):
        return (
            f"{self.employee.employee_code} - "
            f"{self.name} - {self.amount}"
        )
